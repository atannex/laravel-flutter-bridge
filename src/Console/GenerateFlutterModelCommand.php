<?php

declare(strict_types=1);

namespace Atannex\LaravelFlutterBridge\Console;

use Illuminate\Console\Command;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Support\Facades\Schema;
use Illuminate\Support\Str;
use ReflectionClass;

class GenerateFlutterModelCommand extends Command
{
    /**
     * The name and signature of the console command.
     */
    protected $signature = 'flutter:generate-model
                            {model : The Eloquent model class name (e.g. User or Post)}
                            {--output= : Destination path or directory}';

    /**
     * The console command description.
     */
    protected $description = 'Generate a null-safe Dart data model from a Laravel Eloquent model';

    /**
     * Execute the console command.
     */
    public function handle(): int
    {
        $modelInput = (string) $this->argument('model');
        $modelClass = $this->resolveModelClass($modelInput);

        if (!class_exists($modelClass)) {
            $this->error("Eloquent model class '{$modelClass}' not found!");
            return self::FAILURE;
        }

        /** @var Model $instance */
        $instance = new $modelClass();
        $tableName = $instance->getTable();

        $columns = [];
        if (Schema::hasTable($tableName)) {
            $columnNames = Schema::getColumnListing($tableName);
            $casts = $instance->getCasts();

            foreach ($columnNames as $col) {
                $cast = $casts[$col] ?? null;
                $columns[$col] = $this->mapColumnToDartType($col, $cast);
            }
        } else {
            // Fallback to fillable attributes
            foreach ($instance->getFillable() as $col) {
                $columns[$col] = 'String?';
            }
            $columns['id'] = 'int';
            $columns['created_at'] = 'DateTime?';
            $columns['updated_at'] = 'DateTime?';
        }

        $className = class_basename($modelClass);
        $dartCode = $this->generateDartModelClass($className, $columns);

        $outputPath = $this->option('output')
            ?? config('flutter-bridge.generator.output_path', '../flutter-laravel-bridge/lib/src/generated') . '/' . Str::snake($className) . '.g.dart';

        if (!Str::startsWith($outputPath, '/')) {
            $outputPath = base_path($outputPath);
        }

        $dir = dirname($outputPath);
        if (!is_dir($dir)) {
            mkdir($dir, 0755, true);
        }

        file_put_contents($outputPath, $dartCode);

        $this->info("✅ Generated Dart model '{$className}' at: {$outputPath}");
        return self::SUCCESS;
    }

    protected function resolveModelClass(string $input): string
    {
        if (class_exists($input)) {
            return $input;
        }

        $namespace = config('flutter-bridge.generator.model_namespace', 'App\\Models');
        return "{$namespace}\\" . Str::studly($input);
    }

    protected function mapColumnToDartType(string $column, ?string $cast): string
    {
        if ($column === 'id' || Str::endsWith($column, '_id')) {
            return 'int?';
        }

        if (in_array($column, ['created_at', 'updated_at', 'deleted_at', 'email_verified_at', 'last_active_at'], true)) {
            return 'DateTime?';
        }

        return match ($cast) {
            'int', 'integer' => 'int?',
            'real', 'float', 'double', 'decimal' => 'double?',
            'string' => 'String?',
            'bool', 'boolean' => 'bool?',
            'object', 'array', 'json' => 'Map<String, dynamic>?',
            'collection' => 'List<dynamic>?',
            'date', 'datetime', 'custom_datetime', 'timestamp' => 'DateTime?',
            default => 'dynamic',
        };
    }

    /**
     * @param array<string, string> $columns
     */
    protected function generateDartModelClass(string $className, array $columns): string
    {
        $code = "// GENERATED CODE - DO NOT MODIFY BY HAND\n";
        $code .= "// Generated by Laravel Flutter Bridge\n\n";
        $code .= "class {$className} {\n";

        // Properties
        foreach ($columns as $col => $dartType) {
            $camelCol = Str::camel($col);
            $code .= "  final {$dartType} {$camelCol};\n";
        }

        $code .= "\n  const {$className}({\n";
        foreach ($columns as $col => $dartType) {
            $camelCol = Str::camel($col);
            $code .= "    this.{$camelCol},\n";
        }
        $code .= "  });\n\n";

        // fromJson factory
        $code .= "  factory {$className}.fromJson(Map<String, dynamic> json) {\n";
        $code .= "    return {$className}(\n";
        foreach ($columns as $col => $dartType) {
            $camelCol = Str::camel($col);
            if (Str::startsWith($dartType, 'DateTime')) {
                $code .= "      {$camelCol}: json['{$col}'] != null ? DateTime.tryParse(json['{$col}'].toString()) : null,\n";
            } elseif ($dartType === 'int?') {
                $code .= "      {$camelCol}: json['{$col}'] != null ? int.tryParse(json['{$col}'].toString()) : null,\n";
            } elseif ($dartType === 'double?') {
                $code .= "      {$camelCol}: json['{$col}'] != null ? double.tryParse(json['{$col}'].toString()) : null,\n";
            } elseif ($dartType === 'bool?') {
                $code .= "      {$camelCol}: json['{$col}'] as bool?,\n";
            } elseif ($dartType === 'Map<String, dynamic>?') {
                $code .= "      {$camelCol}: json['{$col}'] as Map<String, dynamic>?,\n";
            } else {
                $code .= "      {$camelCol}: json['{$col}'] as {$dartType},\n";
            }
        }
        $code .= "    );\n  }\n\n";

        // toJson
        $code .= "  Map<String, dynamic> toJson() {\n";
        $code .= "    return {\n";
        foreach ($columns as $col => $dartType) {
            $camelCol = Str::camel($col);
            if (Str::startsWith($dartType, 'DateTime')) {
                $code .= "      '{$col}': {$camelCol}?.toIso8601String(),\n";
            } else {
                $code .= "      '{$col}': {$camelCol},\n";
            }
        }
        $code .= "    };\n  }\n";

        $code .= "}\n";
        return $code;
    }
}

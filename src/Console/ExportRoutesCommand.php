<?php

declare(strict_types=1);

namespace Atannex\LaravelFlutterBridge\Console;

use Illuminate\Console\Command;
use Illuminate\Routing\Route;
use Illuminate\Routing\Router;
use Illuminate\Support\Str;

class ExportRoutesCommand extends Command
{
    /**
     * The name and signature of the console command.
     */
    protected $signature = 'flutter:export-routes
                            {--prefix=api : Route prefix to filter}
                            {--output= : Destination path for the generated Dart file}';

    /**
     * The console command description.
     */
    protected $description = 'Export registered Laravel API routes into a strongly-typed Dart route registry';

    /**
     * Execute the console command.
     */
    public function handle(Router $router): int
    {
        $prefix = (string) $this->option('prefix');
        $routes = collect($router->getRoutes()->getRoutes())
            ->filter(function (Route $route) use ($prefix) {
                return Str::startsWith($route->uri(), $prefix);
            })
            ->map(function (Route $route) {
                $methods = array_diff($route->methods(), ['HEAD']);
                return [
                    'uri' => '/' . ltrim($route->uri(), '/'),
                    'name' => $route->getName() ?? Str::slug(str_replace(['/', '{', '}'], ['_', '', ''], $route->uri()), '_'),
                    'methods' => array_values($methods),
                    'action' => $route->getActionName(),
                ];
            })
            ->values();

        $this->info("Found {$routes->count()} API routes matching prefix '{$prefix}'.");

        $outputPath = $this->option('output')
            ?? config('flutter-bridge.generator.output_path', '../flutter-laravel-bridge/lib/src/generated') . '/laravel_routes.g.dart';

        // Resolve absolute or relative path
        if (!Str::startsWith($outputPath, '/')) {
            $outputPath = base_path($outputPath);
        }

        $dir = dirname($outputPath);
        if (!is_dir($dir)) {
            mkdir($dir, 0755, true);
        }

        $dartCode = $this->generateDartContent($routes);
        file_put_contents($outputPath, $dartCode);

        $this->info("✅ Exported Flutter routes to: {$outputPath}");
        return self::SUCCESS;
    }

    /**
     * Generate Dart source code.
     *
     * @param \Illuminate\Support\Collection<int, array{uri: string, name: string, methods: list<string>, action: string}> $routes
     */
    protected function generateDartContent($routes): string
    {
        $content = "// GENERATED CODE - DO NOT MODIFY BY HAND\n";
        $content .= "// Generated by Laravel Flutter Bridge\n\n";
        $content .= "class LaravelApiRoutes {\n";
        $content .= "  LaravelApiRoutes._();\n\n";

        foreach ($routes as $route) {
            $name = Str::camel(str_replace(['.', '-'], '_', $route['name']));
            $uri = $route['uri'];
            $method = implode('|', $route['methods']);

            $content .= "  /// [{$method}] {$uri}\n";
            $content .= "  static const String {$name} = '{$uri}';\n\n";
        }

        $content .= "}\n";
        return $content;
    }
}
